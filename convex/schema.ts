import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

// The Convex Agent component owns thread and message tables (layer 1,
// episodic). Everything here is Dhee's own layer 2 (user model) or
// layer 3 (derived context).
//
// Layer 2 is the product's differentiator and is fully user-visible and
// user-editable on the "Dhee's understanding of you" screen. Anything the
// assistant knows about a person lives in a row they can read and delete.

export const observationKind = v.union(
  v.literal("value"),
  v.literal("relationship"),
  v.literal("aspiration"),
  v.literal("pattern"),
  v.literal("context"),
);

export const inquiryStatus = v.union(
  v.literal("living"),
  v.literal("resolved"),
  v.literal("parked"),
);

export const familiarity = v.union(
  v.literal("new"),
  v.literal("exploring"),
  v.literal("resonating"),
);

export default defineSchema({
  // Our own user row, one per Better Auth user. The component owns the real
  // auth tables (user, session, account, …) inside its own namespace; this is
  // the app-side mirror that every other table here points at, so the seven
  // `v.id("users")` foreign keys below stay real Convex ids rather than
  // opaque strings from a JWT.
  //
  // Kept in step by `triggers.user.onCreate` / `onDelete` in auth.ts. Nothing
  // in the app queries the component to authorize — `requireUserId` resolves
  // `identity.subject` against `by_auth_id` and stops there.
  users: defineTable({
    // The component's user `_id`, which arrives as the JWT subject.
    authId: v.string(),
    email: v.string(),
    name: v.optional(v.string()),
    createdAt: v.number(),
  })
    .index("by_auth_id", ["authId"])
    .index("by_email", ["email"]),

  profiles: defineTable({
    userId: v.id("users"),
    name: v.optional(v.string()),
    preferredLanguage: v.union(v.literal("en"), v.literal("hi")),
    onboarded: v.boolean(),
    createdAt: v.number(),
    // Profile photo, held in Convex file storage. Optional — the initials
    // avatar is the fallback.
    avatarId: v.optional(v.id("_storage")),

    // Personalization. Everything here goes verbatim into the system prompt,
    // and everything here is editable and clearable by the person it
    // describes — the same promise the "understanding of you" screen makes.
    // See docs/build/specs/personalization.md.
    nickname: v.optional(v.string()),
    occupation: v.optional(v.string()),
    aboutYou: v.optional(v.string()),
    // Frameworks the person thinks within. An array rather than the design's
    // comma-joined string because the free/paid distinction is a *count*, and
    // a string would make counting a parsing problem.
    traditions: v.optional(v.array(v.string())),

    // Which model tier answers them — see convex/agents/models.ts.
    //
    // A plain string rather than a union of the tier names on purpose. A tier
    // that is renamed or retired would otherwise make every profile holding the
    // old value fail validation on read, and someone's stored preference is not
    // worth an unreadable profile. `resolveModelTier` narrows it on the way out
    // and falls back to the default, so an unknown value costs the preference
    // and nothing else. Absent means the default, which is what everyone had
    // before this existed.
    preferredModel: v.optional(v.string()),
  }).index("by_user", ["userId"]),

  // The life questions a person is sitting with — the heart of the product.
  inquiries: defineTable({
    userId: v.id("users"),
    question: v.string(),
    status: inquiryStatus,
    firstAskedAt: v.number(),
    threadIds: v.array(v.string()),
    userEdited: v.boolean(),
  }).index("by_user", ["userId"]),

  observations: defineTable({
    userId: v.id("users"),
    kind: observationKind,
    text: v.string(),
    sourceThreadId: v.string(),
    confidence: v.union(v.literal("stated"), v.literal("inferred")),
    createdAt: v.number(),
    userEdited: v.boolean(),
  }).index("by_user", ["userId"]),

  // Which ideas this person has engaged with, stored in plain-language form
  // so this table can be shown to them without translation.
  conceptsTouched: defineTable({
    userId: v.id("users"),
    conceptSlug: v.string(),
    plainLanguageLabel: v.string(),
    familiarity,
    lastTouchedAt: v.number(),
  })
    .index("by_user", ["userId"])
    .index("by_user_concept", ["userId", "conceptSlug"]),

  // Layer 3. Latest row per user wins; regenerated by the extraction workflow.
  contextBlocks: defineTable({
    userId: v.id("users"),
    block: v.string(),
    generatedAt: v.number(),
  }).index("by_user", ["userId"]),

  // Dhee's own per-thread metadata, keyed by the agent component's threadId.
  // Holds the extraction turn counter plus user-set flags (star / pin) that
  // the agent component's thread table doesn't carry.
  threadMeta: defineTable({
    userId: v.id("users"),
    threadId: v.string(),
    turnsSinceExtraction: v.number(),
    // The idle flush queued for this thread, held so the next turn can cancel
    // it and re-queue. Without the id there is no way to debounce, and a busy
    // thread would pile up one extraction per turn.
    pendingExtraction: v.optional(v.id("_scheduled_functions")),
    // Highest agent-component message `order` already extracted. Everything at
    // or below it has been read once, so a later run doesn't pay to re-read
    // it — which is what makes a short interval affordable.
    extractedThroughOrder: v.optional(v.number()),
    starred: v.optional(v.boolean()),
    pinned: v.optional(v.boolean()),
    // UIMessage keys of messages the person rewrote, for the "edited" label.
    editedMessages: v.optional(v.array(v.string())),
    // UIMessage keys of replies the person stopped. A stopped turn and a turn
    // the model failed both finalize as `failed`, and only this tells them
    // apart — a stop must show no error surface at all (spec §7).
    stoppedMessages: v.optional(v.array(v.string())),
    // Raised when something the person wrote suggests they may be in danger,
    // so the support banner survives a reload. Sticky for the life of the
    // thread: it is set, never cleared. A new conversation starts clear.
    crisisFlagged: v.optional(v.boolean()),
  })
    .index("by_thread", ["threadId"])
    .index("by_user", ["userId"]),

  // A conversation published as a read-only link. One active row per thread;
  // revoked rows are kept as tombstones so a slug that was once handed out is
  // never reissued to a different snapshot. See docs/build/specs/sharing.md.
  //
  // `title` and `throughOrder` are frozen copies rather than lookups: a share
  // is a snapshot, so renaming the thread or carrying on the conversation must
  // not change what a link already sent to someone shows.
  sharedThreads: defineTable({
    userId: v.id("users"),
    threadId: v.string(),
    // The public path segment, /s/<slug>. Unguessable is the whole of the
    // access control, so this is random rather than derived from the thread.
    slug: v.string(),
    title: v.optional(v.string()),
    // The agent-component message the snapshot ends at, and its `order`. The
    // id alone is not enough: an edit can delete it, and a dangling id would
    // otherwise read as "no bound" and publish the whole thread.
    throughMessageId: v.string(),
    throughOrder: v.number(),
    createdAt: v.number(),
    revokedAt: v.optional(v.number()),
  })
    .index("by_slug", ["slug"])
    .index("by_thread", ["threadId"])
    .index("by_user", ["userId"]),

  // One row per billed model call, written by the agent's `usageHandler` and by
  // the two call sites that reach the model without going through the agent.
  //
  // This is not a duplicate of what the agent component already stores. The
  // component records usage on the message a call produced — which means the
  // calls that deliberately produce no message record nothing at all. Titling
  // and incognito both pass `saveMessages: "none"`, and memory extraction calls
  // the model directly, so all three are invisible in the component's tables
  // and their spend cannot be told apart from zero.
  //
  // Two further reasons this is its own table rather than a query over the
  // component's: it survives thread deletion, so a person clearing their
  // history doesn't erase the record of what serving them cost; and it is
  // indexed by time, which the component's tables are not, so "what did last
  // week cost" is a range scan rather than a full read.
  //
  // No message text, no prompt, no reply — only counts, and `userId` so cost
  // can be attributed. Nothing here says anything about what was discussed.
  llmUsage: defineTable({
    // Absent when no signed-in person made the call. Today that is only the
    // eval harness, whose rows are filed as `eval`.
    userId: v.optional(v.id("users")),
    threadId: v.optional(v.string()),
    // What the call was for. Named rather than derived, because the whole point
    // is telling apart the work a person sees from the work they don't.
    kind: v.union(
      v.literal("chat"),
      v.literal("title"),
      v.literal("extraction"),
      v.literal("incognito"),
      v.literal("eval"),
    ),
    model: v.string(),
    provider: v.optional(v.string()),
    agentName: v.optional(v.string()),
    promptTokens: v.number(),
    completionTokens: v.number(),
    // Present only when the provider reports it. Absent and zero mean different
    // things — "not told" versus "nothing was cached" — and the cache hit rate
    // is only honest if they stay distinguishable.
    cachedInputTokens: v.optional(v.number()),
    reasoningTokens: v.optional(v.number()),
    // Real money, as billed, when the provider returns it. Never estimated
    // from a price table here: a figure derived from a stale table that looks
    // like a measurement is worse than an absent one.
    costUsd: v.optional(v.number()),
    createdAt: v.number(),
  })
    .index("by_created", ["createdAt"])
    .index("by_user", ["userId", "createdAt"])
    .index("by_kind", ["kind", "createdAt"]),

  // Thumbs up/down on an assistant message. One row per (user, message);
  // messageId is the agent UIMessage key. Cleared when its thread is deleted.
  messageFeedback: defineTable({
    userId: v.id("users"),
    threadId: v.string(),
    messageId: v.string(),
    rating: v.union(v.literal("up"), v.literal("down")),
    createdAt: v.number(),
  })
    .index("by_message", ["messageId"])
    .index("by_thread", ["threadId"])
    .index("by_user", ["userId"]),
});
